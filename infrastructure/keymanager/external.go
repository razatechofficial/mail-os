package keymanager

import (
	"context"
	"errors"
	"fmt"

	app "github.com/razatechofficial/mail-os/application/keymanager"
	domain "github.com/razatechofficial/mail-os/domain/keymanager"
)

// RemoteKEKService is a key service that holds symmetric keys and encrypts
// small values under them without ever releasing a key: AWS KMS (AWSKMS)
// here. Google Cloud KMS (Encrypt/Decrypt with additionalAuthenticatedData),
// Azure Key Vault or Managed HSM (A256GCM encrypt/decrypt, or wrapKey with
// the aad bound separately) and Vault Transit (encrypt/decrypt with
// associated_data) fit the same three calls; none of them is built yet.
type RemoteKEKService interface {
	// Resolve checks keyID names an enabled symmetric encryption key and
	// returns its canonical, stable name (for AWS, the key ARN: an alias
	// can be repointed, an ARN cannot).
	Resolve(ctx context.Context, keyID string) (string, error)
	// Encrypt encrypts plain under keyID, bound to aad.
	Encrypt(ctx context.Context, keyID string, plain, aad []byte) ([]byte, error)
	// Decrypt opens what Encrypt returned for keyID with the same aad.
	Decrypt(ctx context.Context, keyID string, ciphertext, aad []byte) ([]byte, error)
}

// ExternalKEK is a key in a remote key service. Data keys are generated by
// the key manager, wrapped by the service and stored only wrapped; each
// replica unwraps a data key once and keeps it in memory.
type ExternalKEK struct {
	provider string
	svc      RemoteKEKService
	key      string
}

var _ app.KEK = (*ExternalKEK)(nil)

// NewExternalKEK resolves keyID on svc; provider names the service in the
// KEK id (kms).
func NewExternalKEK(ctx context.Context, provider string, svc RemoteKEKService, keyID string) (*ExternalKEK, error) {
	if keyID == "" {
		return nil, fmt.Errorf("%s: a key-encryption key id is required", provider)
	}
	key, err := svc.Resolve(ctx, keyID)
	if err != nil {
		return nil, err
	}
	return &ExternalKEK{provider: provider, svc: svc, key: key}, nil
}

// ID implements app.KEK: <provider>:<canonical key name>.
func (k *ExternalKEK) ID() string { return domain.KEKID(k.provider, k.key) }

// Wrap encrypts a data key under the remote key.
func (k *ExternalKEK) Wrap(ctx context.Context, dek, aad []byte) ([]byte, error) {
	out, err := k.svc.Encrypt(ctx, k.key, dek, aad)
	if err != nil {
		return nil, fmt.Errorf("%s: wrap data key: %w", k.provider, err)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: wrap returned no ciphertext", k.provider)
	}
	return out, nil
}

// Unwrap decrypts a data key with the remote key.
func (k *ExternalKEK) Unwrap(ctx context.Context, wrapped, aad []byte) ([]byte, error) {
	dek, err := k.svc.Decrypt(ctx, k.key, wrapped, aad)
	if err != nil {
		return nil, fmt.Errorf("%s: unwrap data key: %w", k.provider, err)
	}
	if len(dek) != 32 {
		clear(dek)
		return nil, errors.New("data key is not 32 bytes")
	}
	return dek, nil
}
